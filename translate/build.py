#!/usr/bin/env python3
"""Update the translation template and compile translations.

Usage: python3 translate/build.py

1. Extracts every i18n("...") string from the QML files into template.pot.
2. For each <lang>.po in this folder, reports missing or obsolete strings
   and compiles it to contents/locale/<lang>/LC_MESSAGES/<domain>.mo.

Needs only Python 3, no gettext tools.
"""
import ast
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PACKAGE = HERE.parent / "org.andres.desktopname"
DOMAIN = "plasma_applet_org.andres.desktopname"

I18N_CALL = re.compile(r'\bi18n\(\s*("(?:[^"\\]|\\.)*")')


def po_quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def extract():
    """Return {msgid: [locations]} in source order."""
    found = {}
    for qml in sorted(PACKAGE.rglob("*.qml")):
        rel = qml.relative_to(HERE.parent)
        for lineno, line in enumerate(qml.read_text(encoding="utf-8").splitlines(), 1):
            for m in I18N_CALL.finditer(line):
                msgid = ast.literal_eval(m.group(1))
                found.setdefault(msgid, []).append(f"{rel}:{lineno}")
    return found


def write_template(strings):
    out = [
        "# Translation template for the Desktop Name widget.",
        "# Generated by translate/build.py; do not edit by hand.",
        'msgid ""',
        'msgstr ""',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        "",
    ]
    for msgid, locations in strings.items():
        out.append("#: " + " ".join(locations))
        out.append("msgid " + po_quote(msgid))
        out.append('msgstr ""')
        out.append("")
    (HERE / "template.pot").write_text("\n".join(out), encoding="utf-8")


def parse_po(path):
    """Return {msgid: msgstr}, including the "" header entry."""
    entries = {}
    msgid = msgstr = None
    field = None

    def flush():
        if msgid is not None and msgstr is not None:
            entries[msgid] = msgstr

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("msgid "):
            flush()
            msgid, msgstr, field = ast.literal_eval(line[6:]), None, "id"
        elif line.startswith("msgstr "):
            msgstr, field = ast.literal_eval(line[7:]), "str"
        elif line.startswith('"'):
            if field == "id":
                msgid += ast.literal_eval(line)
            else:
                msgstr += ast.literal_eval(line)
    flush()
    return entries


def write_mo(entries, path):
    # Untranslated strings are left out so the English text is shown.
    items = sorted((k, v) for k, v in entries.items() if v)
    ids = [k.encode("utf-8") for k, _ in items]
    strs = [v.encode("utf-8") for _, v in items]
    n = len(items)
    header_size = 7 * 4
    ids_table = header_size
    strs_table = ids_table + n * 8
    data_start = strs_table + n * 8

    data = b""
    id_offsets, str_offsets = [], []
    for s in ids:
        id_offsets.append((len(s), data_start + len(data)))
        data += s + b"\0"
    for s in strs:
        str_offsets.append((len(s), data_start + len(data)))
        data += s + b"\0"

    out = struct.pack("<7I", 0x950412DE, 0, n, ids_table, strs_table, 0, 0)
    for length, offset in id_offsets + str_offsets:
        out += struct.pack("<2I", length, offset)
    out += data

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(out)


def main():
    strings = extract()
    write_template(strings)
    print(f"template.pot: {len(strings)} strings")

    ok = True
    for po in sorted(HERE.glob("*.po")):
        lang = po.stem
        entries = parse_po(po)
        missing = [s for s in strings if not entries.get(s)]
        obsolete = [s for s in entries if s and s not in strings]
        for s in missing:
            print(f"  {lang}: missing translation: {s!r}")
            ok = False
        for s in obsolete:
            print(f"  {lang}: obsolete string: {s!r}")
        entries = {k: v for k, v in entries.items() if k == "" or k in strings}
        mo = PACKAGE / "contents" / "locale" / lang / "LC_MESSAGES" / f"{DOMAIN}.mo"
        write_mo(entries, mo)
        print(f"{lang}.po -> {mo.relative_to(HERE.parent)}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
